from __future__ import annotations

import logging
from pathlib import Path
from django.conf import settings

logger = logging.getLogger(__name__)


def sync_traefik_custom_domains() -> str:
    """
    Scans all verified custom domains in Organization and generates a dynamic
    Traefik configuration file at traefik/dynamic/custom-domains.yml with automated
    Let's Encrypt TLS (certResolver: customdomains).
    """
    from common.tenancy import Organization

    root_dir = getattr(settings, "ROOT_DIR", Path(settings.BASE_DIR).parent)
    dynamic_dir = Path(root_dir) / "traefik" / "dynamic"
    config_file = dynamic_dir / "custom-domains.yml"

    verified_orgs = Organization.objects.filter(
        custom_domain__isnull=False,
        is_active=True,
    ).exclude(custom_domain="")

    lines = [
        "# AUTO-GENERATED by Beamline TraefikSyncService — do not edit manually.",
        "http:",
        "  routers:",
    ]

    count = 0
    for idx, org in enumerate(verified_orgs):
        domain = (org.custom_domain or "").strip().lower()
        if not domain:
            continue
        count += 1
        router_name = f"beamline-custom-{idx}-{org.slug}"
        lines.extend(
            [
                f"    {router_name}:",
                f"      rule: Host(`{domain}`)",
                "      entryPoints:",
                "        - websecure",
                "      service: frontend@docker",
                "      tls:",
                "        certResolver: customdomains",
                "      priority: 85",
            ]
        )

    if count == 0:
        lines.extend(
            [
                "    beamline-custom-placeholder:",
                "      rule: Host(`placeholder.beamline.musfiqdehan.com`)",
                "      entryPoints:",
                "        - websecure",
                "      service: frontend@docker",
                "      priority: 10",
            ]
        )

    content = "\n".join(lines) + "\n"
    try:
        dynamic_dir.mkdir(parents=True, exist_ok=True)
        config_file.write_text(content, encoding="utf-8")
        logger.info(
            "Traefik custom domains updated with %d active tenant domains at %s",
            count,
            config_file,
        )
    except Exception as exc:
        logger.warning("Could not write Traefik custom-domains.yml: %s", exc)

    return content
